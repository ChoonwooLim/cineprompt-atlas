REFERENCES = {
    'camera': ['S01', 'S08', 'S20'],
    'blocking': ['S03', 'S04', 'S06'],
    'action': ['S02', 'S04', 'S06', 'S09'],
    'dialogue': ['S01', 'S04', 'S06'],
    'vehicle': ['S03', 'S08', 'S09'],
    'product': ['S01', 'S03', 'S05'],
    'lighting': ['S01', 'S05'],
    'render': ['S11', 'S12', 'S14', 'S15'],
    'animation': ['S06', 'S08', 'S09'],
    'editing': ['S04', 'S07', 'S15', 'S16'],
    'color': ['S13', 'S14', 'S17', 'S19'],
    'delivery': ['S06', 'S07', 'S15', 'S16'],
}

def main():
    path = ROOT / 'data/prompts.json'
    catalog = json.loads(path.read_text())
    originals = [p for p in catalog if int(p['id'].rsplit('-', 1)[1]) <= 6]
    assert len(originals) == 72
    result = []
    for theme, block in ROWS.items():
        base = [copy.deepcopy(p) for p in originals if p['thumbnailTheme'] == theme]
        assert len(base) == 6, theme
        # Fix a pre-existing escape typo; IDs and original scene content stay stable.
        for p in base:
            p['prompt'] = p['prompt'].replace('{{{{outputDir}}}}', '{{outputDir}}')
        result.extend(base)
        rows = [line.split('|') for line in block.strip().splitlines()]
        assert len(rows) == 14 and all(len(r) == 4 for r in rows), theme
        for n, (title, seconds, direction, criterion) in enumerate(rows, 7):
            item = copy.deepcopy(base[0])
            item.update(id=f'{theme}-{n:02d}', title=title, duration=f'{seconds}초',
                        level='고급' if n in (9, 12, 15, 18, 20) else '중급',
                        tags=list(dict.fromkeys(title.split() + [theme, '프리비즈'])),
                        summary=direction.split('. ')[0] + '.', sourceIds=REFERENCES[theme])
            if theme in ('render', 'color', 'delivery'):
                item['engine'] = '공통'
            item['prompt'] = (
                f'너는 Blender 프리비즈 감독이자 씬 제작 에이전트다. {{{{brief}}}}를 바탕으로 「{title}」 프리셋을 구현하라. '
                f'리뷰 클립 목표 길이는 {seconds}초, 화면비는 {item["aspectRatio"]}, fps는 {{{{fps}}}}, 엔진은 {item["engine"]}다. '
                '검수·비교 프리셋의 길이는 리뷰용 편집 기준이며 실제 계산 시간 제한이 아니다. '
                '설치된 Blender 버전과 지원 API, 장치, 기존 씬을 먼저 조회한다. 공통 엔진이면 프로젝트 엔진을 유지한다.\n\n'
                f'장면 및 작업 지시\n{direction}\n\n'
                '실행 순서\n'
                '1. 브리프에서 필요한 인물·제품·세트·카메라를 정리하고 자산이 없으면 명확히 표시한 대리 모델로 블로킹한다. 기존 씬은 복사본에서 작업한다.\n'
                '2. 샷의 핵심 사건과 시작·전환·종료 프레임을 정한다. 길이와 fps로 전체 프레임 수를 계산하고 단위·렌즈·거리·속도 가정을 기록한다.\n'
                '3. 위 지시의 비교 조건을 한 번에 하나씩 조절한다. 시작·중간·끝 프레임 및 움직임이 큰 연속 구간을 검토하고 결과에 맞춰 수정한다.\n'
                '4. {{outputDir}}에 blend 복사본, 생성 또는 검수 스크립트, 샷리스트, 필요한 비교 프레임과 리뷰 영상, 검수 보고서를 저장한다. 정상 원본 결과를 덮어쓰지 않는다.\n\n'
                f'이 프리셋의 완료 기준\n{criterion}\n'
                '실행한 검수와 미검증 사항을 분리한다. 실행 도구가 없으면 재현 가능한 스크립트와 절차를 제공하고 결과 파일을 만들었다고 말하지 않는다. '
                '설정값은 제작 가정이며 특정 스튜디오의 내부 규격이나 최종 품질 보증이 아니다.'
            )
            item['negativePrompt'] = f'다음 검수 기준을 어기는 결과를 피하라: {criterion} 누락 자산, 근거 없는 완료 보고, 기존 파일 덮어쓰기를 허용하지 않는다.'
            item['variables'][0]['default'] = title + '에 맞는 독창적인 가상 장면'
            item['variables'][2]['default'] = './previs_output/' + item['id']
            item['researchNote'] = '기존에 수집한 공개 자료의 일반 제작·검수 원칙을 참고해 새로 작성한 프리셋입니다. 링크가 이 장면의 모든 설정이나 결과를 직접 검증한다는 뜻은 아닙니다. Blender에서 실제 씬 실행 검수는 별도로 필요합니다.'
            result.append(item)
    assert len(result) == 240
    assert len({p['id'] for p in result}) == 240
    assert len({p['title'] for p in result}) == 240
    assert set(Counter(p['category'] for p in result).values()) == {20}
    source_ids = {s['id'] for s in json.loads((ROOT / 'data/sources.json').read_text())}
    for p in result:
        keys = {v['key'] for v in p['variables']}
        assert set(re.findall(r'{{(\w+)}}', p['prompt'])) == keys, p['id']
        rendered = p['prompt']
        for v in p['variables']:
            rendered = rendered.replace('{{' + v['key'] + '}}', v['default'])
        assert '{{' not in rendered and '}}' not in rendered, p['id']
        assert set(p['sourceIds']) <= source_ids, p['id']
    path.write_text(json.dumps(result, ensure_ascii=False, indent=2) + '\n')
    print(json.dumps(Counter(p['category'] for p in result), ensure_ascii=False))

if __name__ == '__main__':
    main()
